"""
    soft_coulomb_sog(r)

Evaluate the SOG approximation: Σ a_i exp(-b_i r²)
"""
function soft_coulomb_sog(r)
    v = 0.0
    r2 = r * r
    for k in 1:N_SOG
        v += SOG_A[k] * exp(-SOG_B[k] * r2)
    end
    return v
end
