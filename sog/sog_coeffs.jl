# Sum-of-Gaussians decomposition of the soft-Coulomb kernel
# 1/√(1+r²) ≈ Σ_{i=1}^{16} a_i exp(-b_i r²)
# Valid on r ∈ [0, 20], max |error| = 7.22e-7
# All weights positive, well-conditioned (max weight ~ 0.16)

const N_SOG = 16

const SOG_A = [
