def eval_soe(t, s, w):
    result = np.zeros_like(t, dtype=complex)
    for sk, wk in zip(s, w):
        result += wk * np.exp(-sk * t)
    return result.real


def verify(name, s, w):
    t = np.linspace(0, 20, 20000)
    exact = 1.0 / np.sqrt(1.0 + t**2)
    approx = eval_soe(t, s, w)
    abs_err = np.abs(exact - approx)
    max_err = np.max(abs_err)
    mean_err = np.mean(abs_err)
    idx_max = np.argmax(abs_err)

    n_real = int(np.sum(np.abs(s.imag) < 1e-15))
    n_cpx = (len(s) - n_real) // 2
    w_sum = np.sum(w).real

    print(f"\n{'='*60}")
    print(f"{name}  ({len(s)} terms)")
    print(f"{'='*60}")
    print(f"  Domain:       [0, 20]")
    print(f"  Real terms:   {n_real},  Conj pairs: {n_cpx}")
    print(f"  Σ w_k (real): {w_sum:.13f}  (err from 1: {abs(w_sum-1):.3e})")
    print(f"  Min Re(s):    {np.min(s.real):.6e}")
    print(f"  Max abs err:  {max_err:.3e}  (at t = {t[idx_max]:.4f})")
    print(f"  Mean abs err: {mean_err:.3e}")


verify("13-term SOE (no decay constraint)", soe13_s, soe13_w)
